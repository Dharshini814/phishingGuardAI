def generate_dataset():
    """Generate the phishing detection training dataset."""
    import random
    random.seed(42)

    records = []

    # Add legitimate URLs
    for url in LEGITIMATE_URLS:
        records.append({"url": url, "label": 0})

    # Add phishing URLs
    for url in PHISHING_URLS:
        records.append({"url": url, "label": 1})

    # ── Enhanced Phishing Examples ────────────────────────────────────────────
    
    # More banking typosquatting
    banking_typos = [
        "https://onlinessbi.sbi.bank.in/",  # The actual case you found!
        "https://netbanking.hdfcbank.secure.in/login",
        "https://icicibank.netbanking.co.in/signin", 
        "https://kotak-netbanking.com/secure",
        "https://axisbank.secure.co.in/login",
        "https://sbi-netbanking.org/signin",
        "https://hdfc-secure.com/netbanking",
        "https://icici-secure.in/login"
    ]
    
    # Tech company sophisticated spoofing
    tech_spoofing = [
        "https://www.goog1e.com/accounts/signin",
        "https://www.microsοft.com/login",  # Greek omicron
        "https://www.payp4l.com/webapps/mpp/signin",
        "https://www.arnazon.com/ap/signin",
        "https://appleid.apple-verify.com/signin"
    ]
    
    # Add enhanced phishing examples
    for url in banking_typos + tech_spoofing:
        records.append({"url": url, "label": 1})

    # ── Augment with programmatically generated samples ───────────────────────

    # More legitimate patterns
    legit_domains = [
        "github.com", "stackoverflow.com", "reddit.com",
        "wikipedia.org", "bbc.com", "cnn.com", "theguardian.com",
        "techcrunch.com", "medium.com", "dev.to", "hashnode.com",
    ]
    legit_paths = [
        "/article/technology",
        "/news/2024",
        "/blog/post",
        "/docs/getting-started",
        "/help/how-to",
        "/learn/tutorial",
        "/community/forums",
    ]
    for i in range(300):
        domain = random.choice(legit_domains)
        path = random.choice(legit_paths)
        url = f"https://www.{domain}{path}"
        records.append({"url": url, "label": 0})

    # More phishing patterns
    phishing_domains = [
        "verify-account.xyz", "secure-login.ml", "account-update.gq",
        "confirm-identity.cf", "security-alert.info", "account-suspended.ru",
        "login-verify.tk", "update-required.ga", "action-needed.cf",
    ]
    phishing_paths = [
        "/login.php?user=victim&token=abc123&redirect=paypal.com",
        "/signin?email=victim@gmail.com&session=xyz",
        "/verify?account=suspend&confirm=now&redirect=bank.com",
        "/account/confirm?ssn=required&code=123456",
        "/update?credit=card&cvv=required&exp=12/24",
    ]
    for i in range(300):
        domain = random.choice(phishing_domains)
        path = random.choice(phishing_paths)
        scheme = random.choice(["http", "https"])
        url = f"{scheme}://{domain}{path}"
        records.append({"url": url, "label": 1})

    # Short clean legit
    for domain in ["google.com", "apple.com", "amazon.com", "microsoft.com", "facebook.com",
                   "twitter.com", "linkedin.com", "youtube.com", "netflix.com", "github.com"] * 5:
        records.append({"url": f"https://www.{domain}/", "label": 0})

    # IP-based phishing
    for i in range(50):
        ip = f"{random.randint(1,254)}.{random.randint(1,254)}.{random.randint(1,254)}.{random.randint(1,254)}"
        records.append({"url": f"http://{ip}/banking/login?redirect=paypal", "label": 1})

    random.shuffle(records)

    df = pd.DataFrame(records)
    return df


